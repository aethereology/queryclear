"use client";

import { useId, useState } from "react";
import type { AuditRecommendation } from "@/lib/agent-runtime";

export function AuditActionPlan({ recommendations }: { recommendations: AuditRecommendation[] }) {
  const [completed, setCompleted] = useState<Set<number>>(() => new Set());
  const [filter, setFilter] = useState("all");
  const uid = useId();
  const measured = recommendations.filter(r => r.provenance === "measured").length;
  return <section id={`${uid}-actions`} aria-label="Your action plan" className="audit-plan">
    <div className="flex flex-col justify-between gap-4 sm:flex-row sm:items-end">
      <div><p className="mono-label">Your action plan</p><h3 className="mt-3 text-2xl sm:text-3xl">Turn findings into next steps.</h3>
        <p className="mt-2 text-sm text-muted">{measured} evidence-backed {measured === 1 ? "action" : "actions"} · {recommendations.length - measured} modeled {recommendations.length - measured === 1 ? "suggestion" : "suggestions"}</p></div>
      <div className="print-hide"><label htmlFor={`${uid}-filter`} className="mb-2 block text-xs font-medium">Show actions</label>
        <select id={`${uid}-filter`} value={filter} onChange={e => setFilter(e.target.value)} className="min-h-11 border border-line bg-paper px-3 text-sm">
          <option value="all">All actions</option><option value="measured">Evidence-backed</option><option value="estimated">Modeled suggestions</option>
        </select></div>
    </div>
    <div className="card mt-6 p-5 print-hide">
      <div className="flex justify-between gap-4 text-sm"><span>Review progress</span><span role="status">{completed.size} of {recommendations.length} reviewed</span></div>
      <progress className="mt-3 h-2 w-full accent-lime-deep" value={completed.size} max={Math.max(1, recommendations.length)} aria-label="Actions reviewed" />
      <p className="mt-2 text-xs text-muted">A checklist for this session. Reviewed does not mean implemented or verified. Download your report before leaving.</p>
    </div>
    {recommendations.length === 0 ? <p className="card mt-4 p-6 text-sm text-muted">No actions were generated by these checks. Review the coverage below before drawing conclusions about the rest of your website.</p> : null}
    <ol className="mt-4 grid gap-4">
      {recommendations.map((r, index) => <li key={`${r.rank}-${index}`} className={`audit-action card p-5 sm:p-7 ${filter !== "all" && filter !== r.provenance ? "audit-action-filtered" : ""}`}>
        <div className="flex gap-4">
          <span aria-hidden className="font-display text-2xl text-lime-deep">{String(index + 1).padStart(2, "0")}</span>
          <div className="min-w-0 flex-1">
            <div className="flex flex-wrap items-center gap-2"><span className="border border-line bg-paper-2 px-2 py-1 text-xs">{r.provenance === "measured" ? "Evidence-backed" : "Modeled suggestion"}</span><span className="text-xs text-muted">{r.kind}</span></div>
            <h4 className="mt-3 break-words text-lg">{r.title}</h4>
            <p className="mt-2 whitespace-pre-line text-sm leading-relaxed text-muted">{r.rationale}</p>
            {r.provenance !== "measured" ? <p className="mt-2 text-xs text-muted">This is a hypothesis. Confirm a real content gap before making changes.</p> : null}
            <p className="mt-3 text-sm leading-relaxed"><strong>Next step: </strong>{r.action}</p>
            <details className="audit-evidence mt-3 text-xs text-muted"><summary className="cursor-pointer py-2 font-medium text-ink">Evidence and source</summary><p className="mt-2 whitespace-pre-line break-words">{r.evidence || "No supporting evidence was recorded."}</p></details>
            <label className="mt-4 flex min-h-11 cursor-pointer items-center gap-3 text-sm print-hide"><input type="checkbox" checked={completed.has(index)} onChange={() => setCompleted(previous => { const next = new Set(previous); if (next.has(index)) next.delete(index); else next.add(index); return next; })} className="h-5 w-5 accent-lime-deep" />Mark action {index + 1} reviewed</label>
          </div>
        </div>
      </li>)}
    </ol>
    {recommendations.length > 0 && !recommendations.some(r => filter === "all" || r.provenance === filter) ? <p role="status" className="mt-4 text-sm text-muted">No actions in this category. Choose All actions to see the complete plan.</p> : null}
  </section>;
}
