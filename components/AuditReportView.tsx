"use client";

import { AuditActionPlan } from "@/components/AuditActionPlan";
import { AuditReportTools } from "@/components/AuditReportTools";
import { useId, useState } from "react";
import { MonoLabel, Cta } from "@/components/ui";
import { SnapshotCta } from "@/components/SnapshotCta";
import { Reveal, Stagger, StaggerItem } from "@/components/motion";
import { site } from "@/lib/site";
import type { AuditReportData } from "@/lib/agent-runtime";

// Lowercase agent severities mapped to the site's chip palette (see AuditReport.tsx).
const SEV: Record<string, string> = {
  high: "border-amber-200 bg-amber-100 text-amber-900",
  medium: "border-line bg-paper-2 text-muted",
  low: "border-line bg-paper text-muted"
};

const CHIP = "inline-flex w-fit border px-3 py-1 font-mono text-xs font-medium uppercase tracking-wider";

function ModeledBadge() {
  return (
    <span
      className="inline-block border border-line bg-paper-2 px-1.5 py-0.5 font-mono text-[10px] uppercase tracking-wider text-muted"
      title="Generated by a general language-model scenario, not a query to a named answer engine."
    >
      modeled
    </span>
  );
}

export function AuditReportView({ report }: { report: AuditReportData }) {
  const measuredWithoutCitation = report.queries.filter(
    (q) => q.measured && q.cited_count === 0
  ).length;
  const reportId = useId();
  const observedActions = report.recommendations.filter(action => action.provenance === "measured");
  return (
    <div className="audit-report space-y-10">
      <AuditReportTools report={report} />
      <nav aria-label="Report sections" className="print-hide flex flex-wrap gap-2 text-sm">
        {[["overview", "Overview"], ["evidence", "Scope & evidence"], ["findings", "Technical findings"], ["scenarios", "Modeled scenarios"]].map(([id,label]) => <a key={id} href={`#${reportId}-${id}`} className="rounded-lg border border-line bg-paper px-4 py-3 hover:bg-paper-2">{label}</a>)}
      </nav>
      {/* Header */}
      <div id={`${reportId}-overview`} className="card scroll-mt-24 grid items-center gap-6 p-6 lg:grid-cols-[1fr_auto] sm:p-8">
        <div>
          <MonoLabel index="report">Automated search-readiness preview</MonoLabel>
          <h2 className="mt-3 break-all text-2xl sm:text-3xl">{report.domain_url}</h2>
          <p className="mt-1.5 text-sm text-muted">{report.page_title || "(no page title found)"}</p>
        </div>
        <div className="flex flex-wrap gap-8">
          <Stat n={report.findings.length} label="On-page findings" />
          {measuredWithoutCitation > 0 ? (
            <Stat n={measuredWithoutCitation} label="Measured checks without citation" />
          ) : null}
          {report.crawled_urls ? <Stat n={report.crawled_urls.length} label="Pages fetched" /> : null}
          <Stat n={report.queries.filter(q => !q.measured).length} label="Modeled scenarios" />
        </div>
      </div>

      <section className="rounded-2xl bg-paper-2 p-6 sm:p-8" aria-labelledby={`${reportId}-summary`}>
        <MonoLabel>Executive summary</MonoLabel><h3 id={`${reportId}-summary`} className="mt-3 text-xl">Start with the evidence you can check.</h3>
        <p className="mt-3 text-sm leading-relaxed text-muted">This run returned {report.findings.length} on-page {report.findings.length === 1 ? "finding" : "findings"} and {observedActions.length} evidence-backed {observedActions.length === 1 ? "action" : "actions"}. {observedActions.length ? `The first evidence-backed recommendation is “${observedActions[0].title}”.` : "No evidence-backed action was generated by these checks; review the scope before drawing conclusions."} Modeled suggestions are exploratory and require validation.</p>
      </section>
      <section id={`${reportId}-evidence`} className="card scroll-mt-24 p-6 sm:p-8" aria-label="Audit scope and evidence">
        <MonoLabel index="scope">Coverage and confidence</MonoLabel>
        <h3 className="mt-3 text-xl">Know what this preview checked.</h3>
        <p className="mt-2 text-sm text-muted">
          {report.crawled_urls ? `${report.crawled_urls.length} public ${report.crawled_urls.length === 1 ? "page" : "pages"} fetched.` : "Page-by-page coverage was not recorded for this report."}
          {" "}Findings apply to the fetched pages and supported checks, not every page or every search engine.
        </p>
        {report.audited_at ? <p className="mt-2 text-xs text-muted">
          Completed <time dateTime={report.audited_at}>{report.audited_at.replace("T", " ").replace(".000Z", " UTC")}</time>
        </p> : null}
        {report.crawled_urls?.length ? <details className="audit-evidence mt-3 text-sm">
          <summary className="cursor-pointer font-medium">View crawled pages</summary>
          <ul className="mt-3 space-y-2 text-muted">
            {report.crawled_urls.map((url, index) => <li key={`${url}-${index}`} className="break-all">{url}</li>)}
          </ul>
        </details> : null}
        <details className="audit-evidence mt-4 text-sm">
          <summary className="cursor-pointer font-medium">Methodology and sample size</summary>
          {report.methodology ? <dl className="mt-3 grid gap-2 text-muted">
            <div><dt className="inline font-medium">Version: </dt><dd className="inline break-all">{report.methodology.version}</dd></div>
            <div><dt className="inline font-medium">Page limit: </dt><dd className="inline">{report.methodology.crawled_page_limit}</dd></div>
            <div><dt className="inline font-medium">Answer method: </dt><dd className="inline">{report.methodology.visibility_method.replaceAll("-", " ")}</dd></div>
            <div><dt className="inline font-medium">Maximum samples per question: </dt><dd className="inline">{report.methodology.samples_per_query}</dd></div>
          </dl> : <p className="mt-3 text-muted">Methodology version was not recorded for this report. Each scenario below shows its own sample count and evidence label.</p>}
          <a className="mt-3 inline-block underline" href="/audit-methodology">Read the checks, priorities, and limitations</a>
        </details>
        <p className="mt-3 text-xs text-muted">Modeled answer scenarios are exploratory suggestions. Prioritize verified technical issues and business facts before acting on a model-generated hypothesis.</p>
      </section>

      {report.detected_voice ? (
        <Reveal>
          <MonoLabel index="voice">Inferred writing style</MonoLabel>
          <blockquote className="card mt-3 p-6">
            <p className="font-display text-lg leading-relaxed text-ink">
              &ldquo;{report.detected_voice}&rdquo;
            </p>
            <p className="mt-2 text-xs text-muted">
              Inferred from the public copy we fetched. Review the sample below for accuracy and
              brand fit before using it.
            </p>
          </blockquote>
        </Reveal>
      ) : null}

      <AuditActionPlan recommendations={report.recommendations} />

      <section id={`${reportId}-findings`} className="scroll-mt-24">
        <MonoLabel index="02">Technical findings</MonoLabel>
        <h3 className="mt-3 text-2xl sm:text-3xl">On-page readiness.</h3>
        {report.findings.length === 0 ? (
          <p className="card mt-6 p-6 text-sm text-muted">
            No issues were detected by this limited set of on-page checks. This does not establish that the entire website is error-free.
          </p>
        ) : (
          <Stagger className="mt-6 grid gap-3">
            {report.findings.map((f, i) => (
              <StaggerItem key={`${f.code}-${i}`} className="card grid gap-4 p-6 sm:grid-cols-[auto_1fr] sm:items-start">
                <span className={`${CHIP} ${SEV[f.severity] ?? SEV.low}`}>{f.severity}</span>
                <div>
                  <h4 className="text-lg">{f.title}</h4>
                  {f.url ? <p className="mt-2 break-all text-xs text-muted">Observed on: {f.url}</p> : null}
                  <p className="mt-1.5 text-sm leading-relaxed text-muted">{f.detail}</p>
                  <p className="mt-1.5 text-sm leading-relaxed text-muted">
                    <span className="font-medium text-ink">Fix: </span>
                    {f.recommendation}
                  </p>
                </div>
              </StaggerItem>
            ))}
          </Stagger>
        )}
      </section>

      <section id={`${reportId}-scenarios`} className="scroll-mt-24">
        <MonoLabel index="03">Answer scenarios</MonoLabel>
        <h3 className="mt-3 text-2xl sm:text-3xl">
          {report.queries.length} buyer-intent {report.queries.length === 1 ? "scenario" : "scenarios"}
          {" "}generated from your site.
        </h3>
        {report.queries.some((q) => !q.measured) ? (
          <p className="mt-3 max-w-2xl text-xs leading-relaxed text-muted">
            Results marked <ModeledBadge /> come from a general language model generating an answer
            scenario. They are not live checks of ChatGPT, Claude, Google AI Overviews, or another
            named product, and they do not establish visibility or a citation rate.
          </p>
        ) : null}
        <div className="mt-6 overflow-hidden border border-dashed border-line">
          {report.queries.map((q, i) => {
            const brandAbsent = q.cited_count === 0;
            const outcome = q.measured
              ? brandAbsent
                ? "not cited in sample"
                : `cited ${q.cited_count}/${q.samples} samples`
              : brandAbsent
                ? "brand absent in sample"
                : `brand present in ${q.cited_count}/${q.samples} samples`;
            return (
              <div
                key={`${q.engine}-${q.query}`}
                className={`flex flex-col items-start justify-between gap-3 p-5 sm:flex-row sm:items-center ${i % 2 ? "bg-paper-2" : "bg-paper"}`}
              >
                <span className="min-w-0 text-sm text-ink">
                  <span className="mr-2 inline-flex items-center gap-1 border border-line bg-paper px-1.5 py-0.5 font-mono text-[11px] uppercase tracking-wider text-muted">
                    {q.measured ? q.engine.replaceAll("_", " ") : "model scenario"}
                    {!q.measured ? <ModeledBadge /> : null}
                  </span>
                  {q.query}
                </span>
                <span
                  className={`${CHIP} tnum ${!q.measured ? "border-line bg-paper-2 text-muted" : brandAbsent ? "border-red-200 bg-red-100 text-red-800" : "border-pine/20 bg-pine/5 text-pine"}`}
                  title={
                    q.measured && q.samples > 1
                      ? `95% confidence: ${(q.confidence_low * 100).toFixed(0)}%–${(q.confidence_high * 100).toFixed(0)}%`
                      : undefined
                  }
                >
                  {outcome}
                </span>
              </div>
            );
          })}
        </div>
      </section>

      {report.sample_draft ? (
        <section>
          <MonoLabel index="04">Sample fix</MonoLabel>
          <h3 className="mt-3 text-2xl sm:text-3xl">An illustrative draft to verify.</h3>
          <p className="mt-2 max-w-2xl text-xs leading-relaxed text-muted">
            Generated from the public copy fetched for this preview. Confirm every business fact,
            qualification, and claim before using it.
          </p>
          <p className="mt-2 text-sm text-muted">
            {report.queries.some((query) => !query.measured)
              ? "Illustrative answer draft for a modeled buyer question"
              : report.sample_draft.title}
          </p>
          <Draft body={report.sample_draft.body} />
        </section>
      ) : null}

      <OffersCta />
    </div>
  );
}

// Conversion block shown at the bottom of the unlocked report. The free audit
// above is honest about being read-only/estimated; these are the paid next
// steps. Mirrors the homepage offer-ladder logic: `need === null` navigates
// (the $497 audit), otherwise the inquiry overlay opens in place (Upgrade/Build).
function OffersCta() {
  const offers = site.offers.slice(1); // drop the free audit itself
  return (
    <section className="print-hide card bg-pine p-7 text-paper sm:p-9">
      <MonoLabel index="05" tone="inverse">Fix what we found</MonoLabel>
      <h3 className="mt-3 text-2xl text-paper sm:text-3xl">Ready to close the gaps?</h3>
      <p className="mt-3 max-w-xl text-sm leading-relaxed text-paper/70">
        This automated preview is a read-only first pass. When you want a
        human-verified review, transparent scoring, or done-for-you work, here&apos;s where to go.
      </p>
      <Stagger className="mt-7 grid gap-4 sm:grid-cols-3">
        {offers.map((o) => (
          <StaggerItem key={o.name} className="flex flex-col border border-paper/15 bg-pine-2/40 p-5">
            <p className="mono-label !text-lime">{o.price}</p>
            <h4 className="mt-2 text-lg text-paper">{o.name}</h4>
            <p className="mt-1.5 flex-1 text-xs leading-relaxed text-paper/65">{o.desc}</p>
            <div className="mt-4">
              {o.need === null ? (
                <Cta href={o.href} className="w-full">
                  {o.cta}
                </Cta>
              ) : (
                <SnapshotCta href={site.inquiryAnchor} defaultNeed={o.need} className="w-full">
                  {o.cta}
                </SnapshotCta>
              )}
            </div>
          </StaggerItem>
        ))}
      </Stagger>
    </section>
  );
}

function Stat({ n, label }: { n: number; label: string }) {
  return (
    <div>
      <div className="font-display text-3xl leading-none text-lime-deep tnum">{n}</div>
      <div className="mono-label mt-1.5">{label}</div>
    </div>
  );
}

function Draft({ body }: { body: string }) {
  const [open, setOpen] = useState(false);
  const draftId = useId();
  return (
    <div className="mt-4">
      <button
        type="button"
        onClick={() => setOpen((v) => !v)}
        aria-expanded={open}
        aria-controls={draftId}
        className="mono-label text-lime-deep underline print-hide"
      >
        {open ? "Hide draft" : "Show draft"}
      </button>
      <pre id={draftId} className={`audit-draft machine-panel mt-3 max-h-96 whitespace-pre-wrap ${open ? "" : "audit-draft-collapsed"}`}>{body}</pre>
    </div>
  );
}
